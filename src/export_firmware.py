"""
Step 4: export everything the ESP32 needs as C headers.

Writes into firmware/esp32/include/:
  model_data.h   - the INT8 .tflite model as a byte array
  constants.h    - scaler mean/scale, window voltages, alarm threshold
  test_cycles.h  - 4 real discharge cycles from held-out battery B0005
                   (early, mid, late life + one late cycle with a heating ramp)
Also writes results/firmware_expected.csv: what Python computes for the same
4 cycles, so we can check the ESP32 prints the same features.

Run:  python src/export_firmware.py   (after train.py and alarm.py)
"""
import os
import json
import numpy as np
import pandas as pd

from data import ROOT, RESULTS, FEATURES, V_START, V_END, RATED_CAPACITY_AH, \
    load_discharges, compute_features
from alarm import run_alarm, dtdt_ma, add_heating_ramp, TEMP_LIMIT_C, CONSECUTIVE
from train import run_tflite, MODELS, FIRMWARE_TEST_BATTERY

OUT = os.path.join(ROOT, "firmware", "esp32", "include")

# Which B0005 cycles go on the chip (1-based cycle numbers)
TEST_CYCLES = [
    ("early", 1, None),
    ("mid", 84, None),
    ("late", 168, None),
    ("late+fault", 160, {"slope": 0.05, "t0": 1200.0}),  # 0.05 C/s ramp from t = 1200 s
]


def c_float(v):
    """C float literal. 9 significant digits = exact float32 round trip."""
    s = f"{float(v):.9g}"
    if "." not in s and "e" not in s:
        s += ".0"  # "0f" is not valid C, "0.0f" is
    return s + "f"


def c_array(name, values, ctype="float", per_line=8):
    """Format a Python list as a C float array definition."""
    items = [c_float(v) for v in values]
    lines = [", ".join(items[i:i + per_line]) for i in range(0, len(items), per_line)]
    body = ",\n  ".join(lines)
    return f"const {ctype} {name}[{len(values)}] = {{\n  {body}\n}};\n"


def write_model(tflite_bytes):
    hex_vals = [f"0x{b:02x}" for b in tflite_bytes]
    lines = [", ".join(hex_vals[i:i + 12]) for i in range(0, len(hex_vals), 12)]
    with open(os.path.join(OUT, "model_data.h"), "w") as f:
        f.write("// INT8 SoH model (generated by src/export_firmware.py, do not edit)\n")
        f.write("#pragma once\n\n")
        f.write(f"const unsigned int g_model_len = {len(tflite_bytes)};\n")
        f.write("alignas(16) const unsigned char g_model[] = {\n  " + ",\n  ".join(lines) + "\n};\n")


def write_constants(scaler, threshold):
    with open(os.path.join(OUT, "constants.h"), "w") as f:
        f.write("// Constants learned in Python (generated by src/export_firmware.py, do not edit)\n")
        f.write("#pragma once\n\n")
        f.write("// Feature order: " + ", ".join(FEATURES) + "\n")
        f.write(c_array("FEATURE_MEAN", scaler["mean"], per_line=4))
        f.write(c_array("FEATURE_SCALE", scaler["scale"], per_line=4))
        f.write(f"\nconst float V_WINDOW_START = {V_START}f;   // V\n")
        f.write(f"const float V_WINDOW_END = {V_END}f;     // V\n")
        f.write(f"const float RATED_CAPACITY_AH = {RATED_CAPACITY_AH}f;\n\n")
        f.write(f"const float DTDT_THRESHOLD = {threshold:.8g}f;  // C/s (99.9th pct x 1.5)\n")
        f.write(f"const int   ALARM_CONSECUTIVE = {CONSECUTIVE};       // samples in a row\n")
        f.write(f"const float TEMP_LIMIT_C = {TEMP_LIMIT_C}f;        // hard limit\n")


def main():
    os.makedirs(OUT, exist_ok=True)
    with open(os.path.join(MODELS, "soh_int8.tflite"), "rb") as f:
        tflite_bytes = f.read()
    with open(os.path.join(MODELS, "scaler.json")) as f:
        scaler = json.load(f)
    with open(os.path.join(MODELS, "alarm_threshold.json")) as f:
        threshold = json.load(f)["threshold_c_per_s"]

    write_model(tflite_bytes)
    write_constants(scaler, threshold)

    cycles = load_discharges(FIRMWARE_TEST_BATTERY)
    header = ["// 4 real discharge cycles from held-out battery " + FIRMWARE_TEST_BATTERY,
              "// (generated by src/export_firmware.py, do not edit)",
              "#pragma once\n",
              "struct TestCycle {",
              "  const char* label;",
              "  int cycle;          // cycle number in the dataset",
              "  float true_soh;     // capacity / 2.0 Ah, in %",
              "  int n;              // number of samples",
              "  const float* t;     // s",
              "  const float* v;     // V",
              "  const float* i;     // A",
              "  const float* temp;  // C",
              "};\n"]
    arrays, table, expected = [], [], []

    for idx, (label, num, fault) in enumerate(TEST_CYCLES):
        c = cycles[num - 1]
        # Use float32 values, exactly what the ESP32 sees
        t = c["t"].astype(np.float32).astype(float)
        v = c["v"].astype(np.float32).astype(float)
        cur = c["i"].astype(np.float32).astype(float)
        T = c["T"].astype(np.float32).astype(float)
        if fault:
            T = add_heating_ramp(t, T, fault["slope"], fault["t0"]).astype(np.float32).astype(float)
        soh = 100.0 * c["capacity"] / RATED_CAPACITY_AH

        arrays.append(f"// {label}: cycle {num}" + (f", heating ramp {fault['slope']} C/s from t={fault['t0']:.0f} s" if fault else ""))
        for key, vals in [("t", t), ("v", v), ("i", cur), ("temp", T)]:
            arrays.append(c_array(f"c{idx}_{key}", vals))
        table.append(f'  {{"{label}", {num}, {soh:.4f}f, {len(t)}, c{idx}_t, c{idx}_v, c{idx}_i, c{idx}_temp}},')

        # Python reference results for the same samples
        feats = compute_features(t, v, T)
        x = (np.array([feats[k] for k in FEATURES]) - scaler["mean"]) / scaler["scale"]
        pred = run_tflite(tflite_bytes, x.reshape(1, 4))[0] * 100
        k, reason = run_alarm(t, T, threshold)
        expected.append({"label": label, "cycle": num, **{f: round(feats[f], 4) for f in FEATURES},
                         "soh_true": round(soh, 2), "soh_pred_int8": round(float(pred), 2),
                         "alarm_t_s": round(t[k], 1) if k is not None else "",
                         "alarm_reason": reason,
                         "alarm_dtdt": round(dtdt_ma(t, T)[k], 4) if k is not None else ""})

    with open(os.path.join(OUT, "test_cycles.h"), "w") as f:
        f.write("\n".join(header) + "\n")
        f.write("\n".join(arrays) + "\n")
        f.write(f"const int NUM_TEST_CYCLES = {len(TEST_CYCLES)};\n")
        f.write("const TestCycle TEST_CYCLES[] = {\n" + "\n".join(table) + "\n};\n")

    exp = pd.DataFrame(expected)
    exp.to_csv(os.path.join(RESULTS, "firmware_expected.csv"), index=False)
    print(f"Wrote headers to {OUT} (model {len(tflite_bytes)} bytes)")
    print(exp.to_string(index=False))


if __name__ == "__main__":
    main()
